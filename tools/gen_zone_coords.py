#!/usr/bin/env python3
"""Writes ZoneCoords.kt, GlassOS's time zone -> place table for sun times, from IANA tzdb's zone.tab and backward.

    python3 tools/gen_zone_coords.py zone.tab backward \\
        app/src/main/java/io/github/abhishekkaisar/glassos/ZoneCoords.kt --version 2026e

zone.tab (not zone1970.tab, which merges Europe/Oslo and others into one zone) gives each zone's principal city,
rounded here to 0.1 degree. backward adds old names that link to one of those zones (US/Pacific, Europe/Kiev).
Both files are in the public domain. Without --version, a +VERSION file next to zone.tab is used.
"""

import argparse
from fractions import Fraction
from pathlib import Path
import re
import sys

COORD = re.compile(r"^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$")
NAME = re.compile(r"^[A-Za-z][A-Za-z0-9_+\-]*(/[A-Za-z0-9_+\-]+)*$")
LIMIT = 65_535  # bytes in one JVM string constant


def tenths(sign, d, m, s):
    """Degrees + minutes + seconds to whole tenths of a degree, half away from zero (exact arithmetic)."""
    value = int(d) + Fraction(int(m), 60) + Fraction(int(s or 0), 3600)
    t = int(value * 10 + Fraction(1, 2))
    return -t if sign == "-" else t


def read_zones(path):
    zones = {}
    for line in Path(path).read_text(encoding="ascii").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        cols = line.split("\t")
        m = COORD.match(cols[1])
        if not m or not NAME.match(cols[2]):
            sys.exit(f"Unexpected zone.tab row: {line!r}")
        if cols[2] in zones:
            sys.exit(f"zone.tab lists {cols[2]} twice")
        g = m.groups()
        zones[cols[2]] = (tenths(*g[0:4]), tenths(*g[4:8]))
    return zones


def read_links(path):
    links = {}
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        cols = line.split("#", 1)[0].split()
        if len(cols) == 3 and cols[0] == "Link":
            links[cols[2]] = cols[1]
    return links


def aliases(zones, links):
    """Old names whose link (followed through any chain) ends at a zone.tab zone."""
    out = {}
    for name, target in links.items():
        if name in zones:
            continue
        for _ in range(8):
            if target in zones or target not in links:
                break
            target = links[target]
        if target in zones and NAME.match(name):
            out[name] = target
    return out


def block(lines):
    text = "\n".join(lines)
    if len(text.encode("utf-8")) >= LIMIT:
        sys.exit("A table is too large for one JVM string constant; split it.")
    return text


def kotlin(version, zones, alias):
    zone_lines = [f"{n} {lat} {lon}" for n, (lat, lon) in sorted(zones.items())]
    alias_lines = [f"{n} {t}" for n, t in sorted(alias.items())]
    return f'''package io.github.abhishekkaisar.glassos

// Pure (no android.* imports), unit tested on the JVM.
// GENERATED by tools/gen_zone_coords.py from IANA tzdb {version} zone.tab and backward, which are in the public
// domain. Do not edit by hand; run the script with a newer tzdb to refresh it.

/**
 * A rough place for each IANA time zone, for sun times when GlassOS Manager has not set one: the principal city of
 * each of zone.tab's {len(zones)} zones at 0.1° (about 11 km), plus {len(alias)} older names that link to one of them (US/Pacific,
 * Asia/Calcutta, Europe/Kiev). Zones with no place, such as UTC or Etc/GMT+5, give null.
 */
object ZoneCoords {{
    const val TZDB = "{version}"

    /** The zone's place, named after its city ("America/Los_Angeles" is Los Angeles), or null. */
    fun lookup(id: String?): Place? {{
        if (id == null) return null
        val name = aliases[id] ?: id
        val at = places[name] ?: return null
        return Place(at[0] / 10.0, at[1] / 10.0, name.substringAfterLast('/').replace('_', ' '))
    }}

    private val places: Map<String, IntArray> by lazy {{
        ZONES.lineSequence().filter {{ it.isNotBlank() }}.associate {{ line ->
            val f = line.split(' ')
            f[0] to intArrayOf(f[1].toInt(), f[2].toInt())
        }}
    }}

    private val aliases: Map<String, String> by lazy {{
        ALIASES.lineSequence().filter {{ it.isNotBlank() }}.associate {{ line -> line.substringBefore(' ') to line.substringAfter(' ') }}
    }}

    /** "Zone latitude longitude" in tenths of a degree, north and east positive. */
    private const val ZONES = """
{block(zone_lines)}
"""

    /** "Old name zone". */
    private const val ALIASES = """
{block(alias_lines)}
"""
}}
'''


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("zone_tab", type=Path)
    p.add_argument("backward", type=Path)
    p.add_argument("output", type=Path)
    p.add_argument("--version", help="tzdb release, such as 2026e")
    args = p.parse_args()
    version = args.version
    if not version:
        v = args.zone_tab.parent / "+VERSION"
        version = v.read_text().strip() if v.is_file() else ""
    if not re.fullmatch(r"\d{4}[a-z]", version):
        sys.exit("Give the tzdb release with --version (such as 2026e).")
    zones = read_zones(args.zone_tab)
    alias = aliases(zones, read_links(args.backward))
    args.output.write_text(kotlin(version, zones, alias), encoding="utf-8")
    print(f"{args.output}: {len(zones)} zones, {len(alias)} aliases, tzdb {version}")


if __name__ == "__main__":
    main()
